const SIZE_PX: Record<"sm" | "md" | "lg", number> = { sm: 14, md: 18, lg: 22 };

export function PlatformGlyph({
  platform,
  size = "md",
  className,
}: {
  platform: SocialPlatform;
  size?: "sm" | "md" | "lg";
  className?: string;
}) {
  const px = SIZE_PX[size];
  return (
    <svg
      viewBox="0 0 24 24"
      width={px}
      height={px}
      fill="currentColor"
      className={className}
      role="img"
      aria-label={PLATFORMS[platform].label}
    >
      {GLYPHS[platform]}
    </svg>
  );
}

/** A rounded chip with the platform glyph, tinted in the brand colour. */
export function PlatformIcon({
  platform,
  size = "md",
  showColor = true,
  className,
}: {
  platform: SocialPlatform;
  size?: "sm" | "md" | "lg";
  showColor?: boolean;
  className?: string;
}) {
  const meta = PLATFORMS[platform];
  const box =
    size === "sm" ? "h-6 w-6" : size === "lg" ? "h-10 w-10" : "h-8 w-8";
  const glyph = size === "lg" ? "md" : "sm";
  return (
    <span
      className={cn(
        "inline-flex shrink-0 items-center justify-center rounded-lg",
        box,
        className,
      )}
      style={
        showColor
          ? { backgroundColor: meta.soft, color: meta.color }
          : { color: meta.color }
      }
      title={meta.label}
    >
      <PlatformGlyph platform={platform} size={glyph} />
    </span>
  );
}

/** A compact overlapping row of platform icons. */
export function PlatformIconGroup({
  platforms,
  size = "sm",
}: {
  platforms: SocialPlatform[];
  size?: "sm" | "md";
}) {
  return (
    <div className="flex items-center gap-1">
      {platforms.map((p) => (
        <PlatformIcon key={p} platform={p} size={size} />
      ))}
    </div>
  );
}
